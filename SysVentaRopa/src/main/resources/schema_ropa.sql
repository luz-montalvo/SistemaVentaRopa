-- =====================================================================
-- SysVentaRopa - Esquema H2 (según el modelo final modelo_venta_de_ropa.architect)
-- Es idempotente: se ejecuta en cada arranque sin duplicar nada.
-- =====================================================================

CREATE TABLE IF NOT EXISTS Perfil (
    idPerfil INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre   VARCHAR(50) NOT NULL,
    CONSTRAINT PK_Perfil PRIMARY KEY (idPerfil)
);

CREATE TABLE IF NOT EXISTS Usuario (
    idUsuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
    usuario   VARCHAR(80)  NOT NULL,
    clave     VARCHAR(100) NOT NULL,
    idPerfil  INTEGER      NOT NULL,
    CONSTRAINT PK_Usuario PRIMARY KEY (idUsuario),
    CONSTRAINT UQ_Usuario_usuario UNIQUE (usuario),
    CONSTRAINT FK_Usuario_Perfil FOREIGN KEY (idPerfil) REFERENCES Perfil (idPerfil)
);

CREATE TABLE IF NOT EXISTS Cliente (
    idCliente     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    dniruc        VARCHAR(15)  NOT NULL,
    nombres       VARCHAR(120) NOT NULL,
    tipoDocumento VARCHAR(20)  NOT NULL,
    repLegal      VARCHAR(120),
    direccion     VARCHAR(150),
    celular       VARCHAR(15),
    CONSTRAINT PK_Cliente PRIMARY KEY (idCliente),
    CONSTRAINT UQ_Cliente_dniruc UNIQUE (dniruc)
);

CREATE TABLE IF NOT EXISTS UnidadMedida (
    idUnidadMed INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(50) NOT NULL,
    CONSTRAINT PK_UnidadMedida PRIMARY KEY (idUnidadMed)
);

CREATE TABLE IF NOT EXISTS Categoria (
    idCateg INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR(60) NOT NULL,
    CONSTRAINT PK_Categoria PRIMARY KEY (idCateg)
);

CREATE TABLE IF NOT EXISTS Productos (
    idProducto  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(100)  NOT NULL,
    preUnitario DECIMAL(10,2) NOT NULL,
    porceUtil   DECIMAL(5,2)  NOT NULL,
    stock       INTEGER       NOT NULL,
    idUnidadMed INTEGER       NOT NULL,
    idCateg     INTEGER       NOT NULL,
    CONSTRAINT PK_Productos PRIMARY KEY (idProducto),
    CONSTRAINT FK_Productos_UnidadMedida FOREIGN KEY (idUnidadMed) REFERENCES UnidadMedida (idUnidadMed),
    CONSTRAINT FK_Productos_Categoria FOREIGN KEY (idCateg) REFERENCES Categoria (idCateg)
);

CREATE TABLE IF NOT EXISTS Venta (
    idVenta     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fechaVenta  DATE          NOT NULL,
    netoTotal   DECIMAL(10,2) NOT NULL,
    igv         DECIMAL(10,2) NOT NULL,
    precioTotal DECIMAL(10,2) NOT NULL,
    idCliente   INTEGER       NOT NULL,
    idUsuario   INTEGER       NOT NULL,
    CONSTRAINT PK_Venta PRIMARY KEY (idVenta),
    CONSTRAINT FK_Venta_Cliente FOREIGN KEY (idCliente) REFERENCES Cliente (idCliente),
    CONSTRAINT FK_Venta_Usuario FOREIGN KEY (idUsuario) REFERENCES Usuario (idUsuario)
);

CREATE TABLE IF NOT EXISTS VentaDetalle (
    idVentaDetalle INTEGER GENERATED BY DEFAULT AS IDENTITY,
    precioUnit     DECIMAL(10,2) NOT NULL,
    porceUtil      DECIMAL(5,2)  NOT NULL,
    cantidad       INTEGER       NOT NULL,
    netoTotal      DECIMAL(10,2) NOT NULL,
    idVenta        INTEGER       NOT NULL,
    idProducto     INTEGER       NOT NULL,
    CONSTRAINT PK_VentaDetalle PRIMARY KEY (idVentaDetalle),
    CONSTRAINT FK_VentaDetalle_Venta FOREIGN KEY (idVenta) REFERENCES Venta (idVenta),
    CONSTRAINT FK_VentaDetalle_Productos FOREIGN KEY (idProducto) REFERENCES Productos (idProducto)
);

CREATE TABLE IF NOT EXISTS proveedor (
    idProveedor INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ruc         VARCHAR(11)  NOT NULL,
    razonSocial VARCHAR(150) NOT NULL,
    contacto    VARCHAR(120),
    direccion   VARCHAR(150),
    celular     VARCHAR(15),
    email       VARCHAR(100),
    CONSTRAINT PK_proveedor PRIMARY KEY (idProveedor),
    CONSTRAINT UQ_proveedor_ruc UNIQUE (ruc)
);

CREATE TABLE IF NOT EXISTS compras (
    idCompra    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fechaCompra DATE          NOT NULL,
    tipoDoc     VARCHAR(20)   NOT NULL,
    serie       VARCHAR(4)    NOT NULL,
    numDoc      VARCHAR(10)   NOT NULL,
    netoTotal   DECIMAL(10,2) NOT NULL,
    igv         DECIMAL(10,2) NOT NULL,
    precioTotal DECIMAL(10,2) NOT NULL,
    idProveedor INTEGER       NOT NULL,
    idUsuario   INTEGER       NOT NULL,
    CONSTRAINT PK_compras PRIMARY KEY (idCompra),
    CONSTRAINT FK_compras_proveedor FOREIGN KEY (idProveedor) REFERENCES proveedor (idProveedor),
    CONSTRAINT FK_compras_Usuario FOREIGN KEY (idUsuario) REFERENCES Usuario (idUsuario)
);

CREATE TABLE IF NOT EXISTS detalle_compra (
    idDetalleCompra INTEGER GENERATED BY DEFAULT AS IDENTITY,
    precioCompra    DECIMAL(10,2) NOT NULL,
    cantidad        INTEGER       NOT NULL,
    subtotal        DECIMAL(10,2) NOT NULL,
    idCompra        INTEGER       NOT NULL,
    idProducto      INTEGER       NOT NULL,
    CONSTRAINT PK_detalle_compra PRIMARY KEY (idDetalleCompra),
    CONSTRAINT FK_detalle_compra_compras FOREIGN KEY (idCompra) REFERENCES compras (idCompra),
    CONSTRAINT FK_detalle_compra_Productos FOREIGN KEY (idProducto) REFERENCES Productos (idProducto)
);

